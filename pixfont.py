# dấu thanh (nằm trên chữ, trừ dấu nặng nằm dưới)
_TONE = {0x0301: "acute", 0x0300: "grave", 0x0309: "hook", 0x0303: "tilde", 0x0323: "dot"}
# dấu mũ / trăng / móc
_SHAPE = {0x0302: "circ", 0x0306: "breve", 0x031B: "horn"}

_cache = {}


def _normalize(ch):
    """'ấ' -> ('A', {'circ','acute'})"""
    up = ch.upper()
    if up == "Đ":
        return "Đ", set()
    nfd = unicodedata.normalize("NFD", up)
    base = nfd[0]
    marks = set()
    for m in nfd[1:]:
        o = ord(m)
        if o in _TONE:
            marks.add(_TONE[o])
        elif o in _SHAPE:
            marks.add(_SHAPE[o])
    return base, marks


def glyph(ch):
    """Trả về (width, [(x, y), ...]) - y có thể âm (dấu phía trên) hoặc > 6 (dấu nặng)."""
    hit = _cache.get(ch)
    if hit is not None:
        return hit
    base, marks = _normalize(ch)
    rows = GLYPHS.get(base)
    if rows is None:
        rows = GLYPHS["?"]
    w = len(rows[0])
    pts = []
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                pts.append((x, y))
    cx = (w - 1) // 2
    if "horn" in marks:
        pts.append((w, 0))
        pts.append((w, 1))
        w += 1

    def put(x, y):
        pts.append((max(0, min(w - 1, x)), y))

    has_shape = "circ" in marks or "breve" in marks
    if "circ" in marks:
        put(cx, -2)
        put(cx - 1, -1)
        put(cx + 1, -1)
    if "breve" in marks:
        put(cx - 1, -2)
        put(cx + 1, -2)
        put(cx, -1)
    t = -4 if has_shape else -3
    if "acute" in marks:
        put(cx + 1, t)
        put(cx, t + 1)
    if "grave" in marks:
        put(cx - 1, t)
        put(cx, t + 1)
    if "hook" in marks:
        put(cx, t)
        put(cx + 1, t)
        put(cx + 1, t + 1)
    if "tilde" in marks:
        put(cx - 1, t)
        put(cx + 1, t)
        put(cx - 2, t + 1)
        put(cx, t + 1)
    if "dot" in marks:
        put(cx, 8)
    pts = sorted(set(pts))
    _cache[ch] = (w, pts)
    return _cache[ch]


_layout_cache = {}


def layout(text):
    """Trả về (danh sách điểm (x, y), chiều rộng) với 1 điểm = 1 pixel font."""
    hit = _layout_cache.get(text)
    if hit is not None:
        return hit
    pts = []
    x = 0
    for ch in text:
        w, gp = glyph(ch)
        for gx, gy in gp:
            pts.append((x + gx, gy))
        x += w + SPACING
    width = max(0, x - SPACING)
    if len(_layout_cache) > 2000:
        _layout_cache.clear()
    _layout_cache[text] = (pts, width)
    return _layout_cache[text]


def text_width(text, scale=1):
    return layout(text)[1] * scale


def wrap(text, scale, max_w):
    """Ngắt dòng theo từ sao cho mỗi dòng rộng <= max_w."""
    words = text.split(" ")
    lines, cur = [], ""
    for w in words:
        trial = w if not cur else cur + " " + w
        if text_width(trial, scale) <= max_w or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def _validate():
    for k, rows in GLYPHS.items():
        assert len(rows) == CAP_H, (k, len(rows))
        assert len({len(r) for r in rows}) == 1, (k, [len(r) for r in rows])


_validate()
